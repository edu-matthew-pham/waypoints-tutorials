// My path smoke test: add from search and a lesson page, reorder, share link, open as a student. Needs a build in dist/.
import { chromium } from 'playwright-core';
import http from 'node:http';
import { readFileSync, existsSync, statSync } from 'node:fs';
import { join, extname } from 'node:path';
const T = { '.html': 'text/html', '.js': 'text/javascript', '.json': 'application/json', '.css': 'text/css' };
const srv = http.createServer((q, r) => { let p = decodeURIComponent(q.url.split('?')[0]); let f = join('dist', p); if (existsSync(f) && statSync(f).isDirectory()) f = join(f, 'index.html'); if (!existsSync(f)) { r.writeHead(404); return r.end(); } r.writeHead(200, { 'content-type': T[extname(f)] || 'application/octet-stream' }); r.end(readFileSync(f)); }).listen(0);
const base = `http://localhost:${srv.address().port}/`;
const b = await chromium.launch({ executablePath: process.env.CHROME_PATH, args: ['--no-sandbox'] });
const ctx = await b.newContext(); const pg = await ctx.newPage();
const errs = []; pg.on('pageerror', (e) => errs.push(e.message));
const ok = (c, m) => { if (!c) { console.error('FAIL', m); process.exitCode = 1; } else console.log('ok', m); };
await pg.goto(base + 'my-path/');
await pg.fill('#wpt-path-q', 'python loops'); await pg.waitForSelector('.wpt-path-add');
await pg.click('.wpt-path-add'); await pg.waitForFunction(() => /Added/.test(document.querySelector('.wp-results').textContent));
await pg.goto(base + 'code/python-foundations/turtle-intro/');
await pg.click('a:has-text("Add to my path")'); await pg.waitForURL(/my-path\/$/);
await pg.waitForFunction(() => document.querySelectorAll('#wpt-path-list li').length === 2);
ok(true, 'two lessons added (search, lesson page)');
await pg.click('#wpt-path-list li:nth-child(2) button:has-text("Up")');
await pg.fill('#wpt-path-title', 'Loops & fun, week 3'); await pg.fill('#wpt-path-note', 'Do the first, skip\nthe rest.');
const link = await pg.inputValue('#wpt-path-link'); console.log(link);
ok(/#t=.*&n=.*&l=[^,]+,[^,]+$/.test(link), 'link has title, note, two lessons');
const st = await ctx.newPage(); st.on('pageerror', (e) => errs.push(e.message));
await st.goto(link);
await st.waitForFunction(() => document.querySelectorAll('#wpt-path-vlist li').length === 2);
ok((await st.textContent('#wpt-path-vtitle')) === 'Loops & fun, week 3', 'student sees title');
ok((await st.textContent('#wpt-path-vnote')).includes('skip\nthe rest'), 'student sees note');
const hrefs = await st.$$eval('#wpt-path-vlist a', (a) => a.map((x) => x.getAttribute('href') + '|' + x.textContent));
console.log(hrefs); ok(hrefs.every((h) => /^\.\.\/.+\/\|.{4,}/.test(h)) && hrefs[0].includes('turtle-intro'), 'order kept, lessons have titles and normal URLs');
ok(await st.isHidden('#wpt-path-edit'), 'student view has no editor');
await st.goto(base + 'my-path/#l=../../etc/passwd,<script>'); ok(await st.isVisible('#wpt-path-edit'), 'bad slugs ignored');
ok(!errs.length, 'no page errors ' + errs.join(';'));
await b.close(); srv.close();
